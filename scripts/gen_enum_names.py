"""Generate name tables for AzerothCore enums mod-acsdk reports by name (e.g. SpellCastResult).

    python scripts/gen_enum_names.py <azerothcore-wotlk> src/packets/EnumNames.generated.h

Re-run after updating AzerothCore. The output is committed so normal builds need no Python.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ENUMS = [
    ("src/server/shared/SharedDefines.h", "SpellCastResult"),
    ("src/server/shared/SharedDefines.h", "ResponseCodes"),
    ("src/server/game/Entities/Item/Item.h", "InventoryResult"),
    ("src/server/game/Entities/Item/Item.h", "BuyResult"),
    ("src/server/game/Entities/Item/Item.h", "SellResult"),
    ("src/server/game/Quests/QuestDef.h", "QuestFailedReason"),
    ("src/server/game/Loot/LootMgr.h", "LootError"),
]


def parse_enum(text: str, name: str) -> list[tuple[str, int]]:
    m = re.search(rf"enum\s+{name}\b[^{{]*\{{(.*?)\}};", text, re.S)
    if not m:
        raise SystemExit(f"enum {name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    values: list[tuple[str, int]] = []
    current = -1
    for entry in body.split(","):
        entry = entry.strip()
        if not entry:
            continue
        if "=" in entry:
            key, expr = (s.strip() for s in entry.split("=", 1))
            current = int(expr, 0)
        else:
            key = entry
            current += 1
        values.append((key, current))
    return values


def main() -> None:
    ac, out = Path(sys.argv[1]), Path(sys.argv[2])
    lines = [
        "// Generated by scripts/gen_enum_names.py from AzerothCore headers. Do not edit.",
        "#ifndef ACSDK_ENUM_NAMES_GENERATED_H",
        "#define ACSDK_ENUM_NAMES_GENERATED_H",
        "",
        "#include <cstdint>",
        "",
        "namespace acsdk",
        "{",
    ]
    for header, name in ENUMS:
        values = parse_enum((ac / header).read_text(errors="replace"), name)
        lines += [
            f"    inline char const* {name}Name(uint32_t value)",
            "    {",
            "        switch (value)",
            "        {",
        ]
        seen: set[int] = set()
        for key, value in values:
            if value in seen:
                continue
            seen.add(value)
            lines.append(f'            case {value}: return "{key}";')
        lines += ["            default: return nullptr;", "        }", "    }", ""]
    lines += ["}", "", "#endif", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
